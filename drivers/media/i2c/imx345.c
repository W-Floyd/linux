/*
 * The six rails the sensor needs, in the order the vendor's power sequence
 * enables them (regulator_bulk_enable() follows array order).
 *
 * The vendor brings up nine, but the other three belong to the OIS and the
 * actuator, not to the sensor: its own device tree gives them to the ois,
 * actuator, aperture and eeprom sub-devices. Dropping them was verified on
 * hardware -- the sensor still probes. Dropping any of the six below is not
 * survivable; with only vana, vio and vdig the chip ID read returns -ENXIO.
 *
 * What vcustom1/2/10 actually feed is undocumented; the names mirror the
 * vendor's own so the mapping back to the stock device tree stays traceable.
 */
static const char * const imx345_supply_name[] = {
	"vio",		/* Interface (1.8V) */
	"vdig",		/* Digital core (1.0V) */
	"vcustom1",	/* 2.85V */
	"vcustom2",	/* 1.1V */
	"vana",		/* Analog (3.2V) */
	"vcustom10",	/* 1.1V */
};

