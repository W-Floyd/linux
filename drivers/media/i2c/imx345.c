#define IMX345_REG_MODE_SELECT		0x0100
#define IMX345_MODE_STANDBY		0x00
#define IMX345_MODE_STREAMING		0x01

#define IMX345_REG_CHIP_ID		0x0016
#define IMX345_CHIP_ID			0x0345

/* V-timing */
#define IMX345_REG_FLL			0x0340
#define IMX345_FLL_MAX			0xffff

/* H-timing */
#define IMX345_REG_LLP			0x0342

#define IMX345_REG_EXPOSURE		0x0202
#define IMX345_EXPOSURE_MIN		1
#define IMX345_EXPOSURE_STEP		1
#define IMX345_EXPOSURE_DEFAULT		0x0282
/* Frame length lines minus this is the maximum coarse integration time */
#define IMX345_EXPOSURE_OFFSET		10

/* Analogue gain is gain = 1024 / (1024 - code) */
#define IMX345_REG_ANALOG_GAIN		0x0204
#define IMX345_ANA_GAIN_MIN		0
#define IMX345_ANA_GAIN_MAX		960
#define IMX345_ANA_GAIN_STEP		1
#define IMX345_ANA_GAIN_DEFAULT		0

/* Digital gain is a 8.8 fixed point multiplier, 0x0100 being unity */
#define IMX345_REG_DIG_GAIN		0x020e
#define IMX345_DGTL_GAIN_MIN		256
#define IMX345_DGTL_GAIN_MAX		4095
#define IMX345_DGTL_GAIN_STEP		1
#define IMX345_DGTL_GAIN_DEFAULT	256

#define IMX345_REG_TEST_PATTERN		0x0600
#define IMX345_TEST_PATTERN_DISABLE	0

#define IMX345_XCLK_FREQ		24000000
#define IMX345_DATA_LANES		4
#define IMX345_RGB_DEPTH		10

/*
 * Power-up timing, measured from the stock kernel with ftrace. The rear module
 * starts MCLK *before* releasing XCLR, the opposite of the front sensor on
 * this board:
 *
 *	rails -> MCLK on -> 2.1 ms -> XCLR high -> 11.8 ms -> first CCI transfer
 */
#define IMX345_MCLK_TO_XCLR_US		3000
#define IMX345_XCLR_TO_I2C_US		12000
#define IMX345_DELAY_RANGE_US		1000

struct imx345_reg {
	u16 address;
	u8 val;
};

struct imx345_reg_list {
	u32 num_of_regs;
	const struct imx345_reg *regs;
};

struct imx345_mode {
	u32 width;
	u32 height;

	/* Frame length lines, as programmed by reg_list */
	u32 fll_def;
	u32 fll_min;

	/* Line length pixels, as programmed by reg_list */
	u32 llp;

	/* Index into imx345_link_freq_menu[] */
	u32 link_freq_index;

	struct imx345_reg_list reg_list;
};

/*
 * Computed as pixel_clock * bits_per_pixel / (2 * lanes) from the pixel clock
 * the sensormodule blob declares per mode. UNVERIFIED -- see the file header.
 */
static const s64 imx345_link_freq_menu[] = {
	675000000,	/* 2016x1512, 540 MHz pixel clock */
	702000000,	/* 4032x3024, 561.6 MHz pixel clock */
};

